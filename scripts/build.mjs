import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { build } from "tsdown";

const root = process.cwd();
await build({
  config: false,
  entry: ["src/gui/client.ts"],
  outDir: ".build",
  platform: "browser",
  target: "es2022",
  format: "iife",
  fixedExtension: false,
  minify: true,
  dts: false,
  deps: { alwaysBundle: [/.*/] },
});
const scripts = fs
  .readdirSync(".build")
  .filter((file) => file.endsWith(".js") || file.endsWith(".mjs"));
if (scripts.length !== 1) throw new Error("Expected one bundled GUI script.");
const browser = fs.readFileSync(path.join(root, ".build", scripts[0]), "utf8");
fs.writeFileSync(
  "src/gui/client.generated.ts",
  `// Generated by scripts/build.mjs. Do not edit.\nexport const GUI_JS = ${JSON.stringify(browser)};\n`,
);
await build();

const pkg = JSON.parse(fs.readFileSync("package.json", "utf8"));
const visited = new Set();
const notices = ["Human Hindsight includes the following open-source libraries.\n"];
function packageDirectory(name, parent) {
  const require = createRequire(path.join(parent, "package.json"));
  try {
    let dir = path.dirname(require.resolve(name));
    while (dir !== path.dirname(dir)) {
      const candidate = path.join(dir, "package.json");
      if (fs.existsSync(candidate) && JSON.parse(fs.readFileSync(candidate, "utf8")).name === name)
        return dir;
      dir = path.dirname(dir);
    }
  } catch {
    // Type-only packages have no executable entry.
    const dir = path.join(root, "node_modules", name);
    if (fs.existsSync(path.join(dir, "package.json"))) return dir;
  }
  throw new Error(`Cannot find bundled package ${name}`);
}
function collect(name, parent) {
  const dir = packageDirectory(name, parent);
  const info = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  const key = `${info.name}@${info.version}`;
  if (visited.has(key)) return;
  visited.add(key);
  const licenses = fs
    .readdirSync(dir)
    .filter(
      (file) =>
        /^(licen[sc]e|copying|notice)(?:[.-]|$)/i.test(file) &&
        fs.statSync(path.join(dir, file)).isFile(),
    );
  if (!licenses.length) throw new Error(`Missing license text for ${key}`);
  notices.push(`\n${"=".repeat(72)}\n${key} — ${info.license}\n`);
  for (const file of licenses) notices.push(fs.readFileSync(path.join(dir, file), "utf8"));
  for (const dependency of Object.keys(info.dependencies ?? {}).sort()) collect(dependency, dir);
}
for (const name of Object.keys(pkg.dependencies).sort()) collect(name, root);
fs.writeFileSync("dist/THIRD_PARTY_NOTICES.txt", notices.join("\n"));
